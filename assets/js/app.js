document.addEventListener("DOMContentLoaded", function () {
  "use strict";

  /* =====================================================
     SEARCH
  ===================================================== */

  const searchPanel = document.getElementById("search-panel");
  const openSearch = document.getElementById("open-search");
  const mobileSearch = document.getElementById("mobile-search");
  const closeSearch = document.getElementById("close-search");
  const searchInput = document.getElementById("site-search");
  const searchResults = document.getElementById("search-results");


  /*
   * Search index generated by Jekyll.
   * Contains ALL published posts.
   */

  let searchIndex = [];

  const searchIndexElement =
    document.getElementById("search-index");

  if (searchIndexElement) {
    try {
      searchIndex =
        JSON.parse(searchIndexElement.textContent || "[]");

      if (!Array.isArray(searchIndex)) {
        searchIndex = [];
      }

    } catch (error) {
      console.error(
        "Infograf+ search index error:",
        error
      );

      searchIndex = [];
    }
  }


  /* =====================================================
     OPEN SEARCH
  ===================================================== */

  function showSearch() {

    if (!searchPanel) {
      return;
    }

    searchPanel.hidden = false;

    document.body.style.overflow = "hidden";

    if (searchInput) {
      setTimeout(function () {
        searchInput.focus();
      }, 50);
    }
  }


  /* =====================================================
     CLOSE SEARCH
  ===================================================== */

  function hideSearch() {

    if (!searchPanel) {
      return;
    }

    searchPanel.hidden = true;

    document.body.style.overflow = "";

    if (searchInput) {
      searchInput.value = "";
    }

    if (searchResults) {
      searchResults.innerHTML = "";
    }
  }


  /* =====================================================
     SEARCH BUTTONS
  ===================================================== */

  if (openSearch) {

    openSearch.addEventListener(
      "click",
      function (event) {

        event.preventDefault();

        showSearch();
      }
    );
  }


  if (mobileSearch) {

    mobileSearch.addEventListener(
      "click",
      function (event) {

        event.preventDefault();

        showSearch();
      }
    );
  }


  if (closeSearch) {

    closeSearch.addEventListener(
      "click",
      function (event) {

        event.preventDefault();

        hideSearch();
      }
    );
  }


  /* =====================================================
     CLOSE WHEN CLICKING OUTSIDE
  ===================================================== */

  if (searchPanel) {

    searchPanel.addEventListener(
      "click",
      function (event) {

        if (event.target === searchPanel) {
          hideSearch();
        }

      }
    );
  }


  /* =====================================================
     ESC
  ===================================================== */

  document.addEventListener(
    "keydown",
    function (event) {

      if (event.key === "Escape") {
        hideSearch();
      }

    }
  );


  /* =====================================================
     ARABIC NORMALIZATION
  ===================================================== */

  function normalizeArabic(text) {

    return String(text || "")
      .toLowerCase()

      /* Remove tashkeel */
      .replace(/[\u064B-\u065F\u0670]/g, "")

      /* Normalize Alif */
      .replace(/[إأآٱ]/g, "ا")

      /* Normalize Ya */
      .replace(/ى/g, "ي")

      /* Normalize Waw */
      .replace(/ؤ/g, "و")

      /* Normalize Hamza */
      .replace(/ئ/g, "ي")

      /* Normalize Ta Marbuta */
      .replace(/ة/g, "ه")

      /* Remove Tatweel */
      .replace(/ـ/g, "")

      /* Normalize spaces */
      .replace(/\s+/g, " ")

      .trim();
  }


  /* =====================================================
     HTML ESCAPE
  ===================================================== */

  function escapeHtml(text) {

    return String(text || "")
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;")
      .replace(/'/g, "&#039;");
  }


  function escapeAttribute(text) {

    return escapeHtml(text);
  }


  /* =====================================================
     SEARCH SCORE
  ===================================================== */

  function scorePost(post, query) {

    const title =
      normalizeArabic(post.title || "");

    const description =
      normalizeArabic(post.description || "");

    const category =
      normalizeArabic(post.category || "");

    let score = 0;


    /*
     * Exact title
     */
    if (title === query) {
      score += 1000;
    }


    /*
     * Title starts with search
     */
    if (title.startsWith(query)) {
      score += 600;
    }


    /*
     * Title contains search
     */
    if (title.includes(query)) {
      score += 400;
    }


    /*
     * Category
     */
    if (category === query) {
      score += 250;
    }

    if (category.includes(query)) {
      score += 150;
    }


    /*
     * Description
     */
    if (description.includes(query)) {
      score += 80;
    }


    /*
     * Multi-word search
     */

    const words =
      query
        .split(/\s+/)
        .filter(function (word) {
          return word.length > 1;
        });


    words.forEach(function (word) {

      if (title.includes(word)) {
        score += 100;
      }

      if (category.includes(word)) {
        score += 50;
      }

      if (description.includes(word)) {
        score += 25;
      }

    });


    return score;
  }


  /* =====================================================
     SEARCH RESULTS
  ===================================================== */

  function performSearch(query) {

    if (!searchResults) {
      return;
    }


    const originalQuery =
      String(query || "").trim();


    const cleanQuery =
      normalizeArabic(originalQuery);


    /*
     * Don't show results until there are at least
     * two meaningful characters.
     */

    if (cleanQuery.length < 2) {

      searchResults.innerHTML = "";

      return;
    }


    /*
     * Search ALL posts.
     */

    const matches =
      searchIndex
        .map(function (post) {

          return {
            post: post,
            score: scorePost(
              post,
              cleanQuery
            )
          };

        })

        .filter(function (result) {

          return result.score > 0;

        })

        .sort(function (a, b) {

          /*
           * Best match first.
           */

          if (b.score !== a.score) {
            return b.score - a.score;
          }


          /*
           * Newer posts first if score is equal.
           */

          const dateA =
            String(a.post.date || "");

          const dateB =
            String(b.post.date || "");

          return dateB.localeCompare(dateA);

        })

        .map(function (result) {

          return result.post;

        });


    /* =================================================
       NO RESULTS
    ================================================= */

    if (matches.length === 0) {

      searchResults.innerHTML =
        '<div class="no-results">' +
        'لا توجد نتائج مطابقة لـ «' +
        escapeHtml(originalQuery) +
        '».' +
        '</div>';

      return;
    }


    /* =================================================
       RESULT COUNT
    ================================================= */

    let html =
      '<div class="search-result-count">' +
      'تم العثور على ' +
      matches.length +
      ' إنفوغرافيك' +
      '</div>';


    /* =================================================
       RESULTS
    ================================================= */

    /*
     * Show maximum 12 suggestions in the search panel.
     */

    const visibleMatches =
      matches.slice(0, 12);


    visibleMatches.forEach(
      function (post) {

        const title =
          post.title ||
          "إنفوغرافيك";


        const category =
          post.category ||
          "";


        const description =
          post.description ||
          "";


        const url =
          post.url ||
          "#";


        html +=
          '<a class="search-result" href="' +
          escapeAttribute(url) +
          '">' +

          '<strong>' +
          escapeHtml(title) +
          '</strong>' +

          (
            category
              ? '<span>' +
                escapeHtml(category) +
                '</span>'
              : ""
          ) +

          (
            description
              ? '<small>' +
                escapeHtml(description) +
                '</small>'
              : ""
          ) +

          '</a>';
      }
    );


    /*
     * If more than 12 results exist,
     * tell the visitor.
     */

    if (matches.length > 12) {

      html +=
        '<div class="search-more">' +
        'هناك ' +
        matches.length +
        ' نتيجة — يتم عرض أول 12.' +
        '</div>';
    }


    searchResults.innerHTML = html;
  }


  /* =====================================================
     SEARCH INPUT
  ===================================================== */

  if (searchInput) {

    searchInput.addEventListener(
      "input",
      function () {

        performSearch(
          searchInput.value
        );

      }
    );
  }


  /* =====================================================
     KEYBOARD SHORTCUT
  ===================================================== */

  document.addEventListener(
    "keydown",
    function (event) {

      /*
       * Ctrl + K
       * Cmd + K
       */

      if (
        (event.ctrlKey || event.metaKey) &&
        event.key.toLowerCase() === "k"
      ) {

        event.preventDefault();

        showSearch();
      }

    }
  );


  /* =====================================================
     HOME CATEGORY FILTER
  ===================================================== */

  const categoryButtons =
    Array.from(
      document.querySelectorAll(
        ".category-chip"
      )
    );


  const homeCards =
    Array.from(
      document.querySelectorAll(
        "#infographic-grid .infographic-card"
      )
    );


  categoryButtons.forEach(
    function (button) {

      /*
       * Only activate JavaScript filtering
       * when data-category exists.
       */

      if (!button.dataset.category) {
        return;
      }


      button.addEventListener(
        "click",
        function (event) {

          event.preventDefault();


          const selectedCategory =
            button.dataset.category ||
            "all";


          categoryButtons.forEach(
            function (item) {

              item.classList.remove(
                "active"
              );

            }
          );


          button.classList.add(
            "active"
          );


          homeCards.forEach(
            function (card) {

              const cardCategory =
                (
                  card.dataset.category ||
                  ""
                ).trim();


              if (
                selectedCategory === "all" ||
                cardCategory === selectedCategory
              ) {

                card.style.display = "";

              } else {

                card.style.display = "none";

              }

            }
          );

        }
      );

    }
  );


  /* =====================================================
     INITIALIZE
  ===================================================== */

  if (searchPanel) {
    searchPanel.hidden = true;
  }


  console.log(
    "Infograf+ loaded successfully."
  );


  console.log(
    "Search index:",
    searchIndex.length,
    "posts"
  );

});
