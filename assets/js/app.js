document.addEventListener("DOMContentLoaded", function () {
  "use strict";

  /* =========================================================
     HELPERS
  ========================================================= */

  function normalizeArabic(text) {
    return String(text || "")
      .toLowerCase()
      .normalize("NFD")
      .replace(/[\u064B-\u065F\u0670]/g, "")
      .replace(/[إأآٱ]/g, "ا")
      .replace(/ى/g, "ي")
      .replace(/ؤ/g, "و")
      .replace(/ئ/g, "ي")
      .replace(/ة/g, "ه")
      .replace(/ـ/g, "")
      .replace(/\s+/g, " ")
      .trim();
  }

  function escapeHtml(text) {
    return String(text || "")
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;")
      .replace(/'/g, "&#039;");
  }

  function escapeAttribute(text) {
    return escapeHtml(text).replace(/`/g, "&#096;");
  }


  /* =========================================================
     SEARCH
  ========================================================= */

  const searchPanel = document.getElementById("search-panel");
  const searchInput = document.getElementById("search-input");
  const searchResults = document.getElementById("search-results");

  const openSearchButtons = document.querySelectorAll(
    "[data-open-search], .search-button, #open-search"
  );

  const closeSearchButtons = document.querySelectorAll(
    "[data-close-search], .close-search, #close-search"
  );

  let searchIndex = [];

  /*
   * Read the complete search index generated by the homepage.
   * This means the search can find published infographics
   * even if they are not currently visible as homepage cards.
   */
  const searchIndexElement = document.getElementById("search-index");

  if (searchIndexElement) {
    try {
      const parsedIndex = JSON.parse(searchIndexElement.textContent || "[]");

      if (Array.isArray(parsedIndex)) {
        searchIndex = parsedIndex;
      }
    } catch (error) {
      console.error("Infograf+ search index error:", error);
      searchIndex = [];
    }
  }


  function showSearch() {
    if (!searchPanel) return;

    searchPanel.classList.add("is-open");
    searchPanel.setAttribute("aria-hidden", "false");

    document.body.classList.add("search-open");

    if (searchInput) {
      setTimeout(function () {
        searchInput.focus();
      }, 50);
    }
  }


  function hideSearch() {
    if (!searchPanel) return;

    searchPanel.classList.remove("is-open");
    searchPanel.setAttribute("aria-hidden", "true");

    document.body.classList.remove("search-open");

    if (searchInput) {
      searchInput.value = "";
    }

    if (searchResults) {
      searchResults.innerHTML = "";
    }
  }


  openSearchButtons.forEach(function (button) {
    button.addEventListener("click", function (event) {
      event.preventDefault();
      showSearch();
    });
  });


  closeSearchButtons.forEach(function (button) {
    button.addEventListener("click", function (event) {
      event.preventDefault();
      hideSearch();
    });
  });


  document.addEventListener("keydown", function (event) {
    if (event.key === "Escape") {
      hideSearch();
    }
  });


  if (searchPanel) {
    searchPanel.addEventListener("click", function (event) {
      /*
       * Close when clicking the overlay itself,
       * but not when clicking inside the search box.
       */
      if (event.target === searchPanel) {
        hideSearch();
      }
    });
  }


  /*
   * Score each result.
   *
   * Higher score = more relevant.
   *
   * Priority:
   * 1. Exact title
   * 2. Title starts with query
   * 3. Title contains query
   * 4. Category match
   * 5. Description match
   */
  function scoreResult(item, query) {
    const title = normalizeArabic(item.title);
    const description = normalizeArabic(item.description);
    const category = normalizeArabic(item.category);

    let score = 0;

    if (!query) {
      return 0;
    }

    if (title === query) {
      score += 1000;
    }

    if (title.startsWith(query)) {
      score += 500;
    }

    if (title.includes(query)) {
      score += 300;
    }

    if (category === query) {
      score += 200;
    }

    if (category.includes(query)) {
      score += 100;
    }

    if (description.includes(query)) {
      score += 50;
    }

    /*
     * Reward matching individual words.
     * This makes multi-word searches more useful.
     */
    const words = query
      .split(/\s+/)
      .filter(function (word) {
        return word.length > 1;
      });

    words.forEach(function (word) {
      if (title.includes(word)) {
        score += 80;
      }

      if (category.includes(word)) {
        score += 40;
      }

      if (description.includes(word)) {
        score += 20;
      }
    });

    return score;
  }


  function performSearch(query) {
    if (!searchResults) return;

    const normalizedQuery = normalizeArabic(query);

    if (!normalizedQuery) {
      searchResults.innerHTML = "";
      return;
    }

    /*
     * Search through title, description and category.
     */
    const results = searchIndex
      .map(function (item) {
        return {
          item: item,
          score: scoreResult(item, normalizedQuery)
        };
      })
      .filter(function (result) {
        return result.score > 0;
      })
      .sort(function (a, b) {
        /*
         * Highest relevance first.
         * If relevance is equal, keep newest items first
         * when a date is available.
         */
        if (b.score !== a.score) {
          return b.score - a.score;
        }

        const dateA = String(a.item.date || "");
        const dateB = String(b.item.date || "");

        return dateB.localeCompare(dateA);
      })
      .map(function (result) {
        return result.item;
      });


    if (results.length === 0) {
      searchResults.innerHTML = `
        <div class="search-empty">
          <strong>لا توجد نتائج</strong>
          <span>جرّب كلمة أخرى أو عبارة مختلفة.</span>
        </div>
      `;

      return;
    }


    /*
     * Limit displayed results so a very large index
     * does not create an unnecessarily long panel.
     */
    const visibleResults = results.slice(0, 30);


    let html = `
      <div class="search-result-count">
        تم العثور على ${results.length} نتيجة
      </div>

      <div class="search-result-list">
    `;


    visibleResults.forEach(function (item) {
      const title = escapeHtml(item.title || "بدون عنوان");
      const description = escapeHtml(item.description || "");
      const category = escapeHtml(item.category || "");
      const url = escapeAttribute(item.url || "#");


      html += `
        <a class="search-result-item" href="${url}">
          <div class="search-result-content">

            ${
              category
                ? `<span class="search-result-category">${category}</span>`
                : ""
            }

            <h3 class="search-result-title">
              ${title}
            </h3>

            ${
              description
                ? `<p class="search-result-description">${description}</p>`
                : ""
            }

          </div>

          <span class="search-result-arrow" aria-hidden="true">
            ←
          </span>
        </a>
      `;
    });


    html += `
      </div>
    `;


    if (results.length > 30) {
      html += `
        <div class="search-more">
          يتم عرض أول 30 نتيجة من أصل ${results.length}.
        </div>
      `;
    }


    searchResults.innerHTML = html;
  }


  if (searchInput) {
    searchInput.addEventListener("input", function () {
      performSearch(searchInput.value);
    });
  }


  /* =========================================================
     HOME CATEGORY FILTER
  ========================================================= */

  /*
   * This section is ONLY for category chips that exist
   * directly on the homepage.
   *
   * The full categories page has its own filtering system
   * inside categories.html.
   */

  const homeCategoryButtons = document.querySelectorAll(
    ".category-chip[data-category]"
  );

  const homeCards = document.querySelectorAll(
    ".infographic-card[data-category]"
  );


  if (homeCategoryButtons.length && homeCards.length) {
    homeCategoryButtons.forEach(function (button) {
      button.addEventListener("click", function (event) {
        /*
         * If the category chip is a normal link to the
         * categories page, don't interfere with navigation.
         */
        const href = button.getAttribute("href");

        if (href && href !== "#") {
          return;
        }

        event.preventDefault();

        const selectedCategory = normalizeArabic(
          button.dataset.category || ""
        );


        homeCategoryButtons.forEach(function (item) {
          item.classList.remove("active");
        });

        button.classList.add("active");


        homeCards.forEach(function (card) {
          const cardCategory = normalizeArabic(
            card.dataset.category || ""
          );

          if (
            selectedCategory === "all" ||
            selectedCategory === "" ||
            cardCategory === selectedCategory
          ) {
            card.hidden = false;
          } else {
            card.hidden = true;
          }
        });
      });
    });
  }


  /* =========================================================
     GLOBAL SEARCH SHORTCUT
  ========================================================= */

  document.addEventListener("keydown", function (event) {
    /*
     * Ctrl + K on Windows/Linux
     * Cmd + K on macOS
     */
    if (
      (event.ctrlKey || event.metaKey) &&
      event.key.toLowerCase() === "k"
    ) {
      event.preventDefault();
      showSearch();
    }
  });


  /* =========================================================
     INITIAL STATE
  ========================================================= */

  if (searchPanel) {
    searchPanel.setAttribute("aria-hidden", "true");
  }


  console.log("Infograf+ loaded.");

  if (searchIndex.length) {
    console.log(
      "Infograf+ search index:",
      searchIndex.length,
      "items"
    );
  } else {
    console.log("Infograf+ search index is empty or unavailable.");
  }
});
