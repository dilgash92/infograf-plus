document.addEventListener("DOMContentLoaded", function () {

  /* =====================================================
     SEARCH
  ===================================================== */

  const searchPanel = document.getElementById("search-panel");
  const openSearch = document.getElementById("open-search");
  const mobileSearch = document.getElementById("mobile-search");
  const closeSearch = document.getElementById("close-search");
  const searchInput = document.getElementById("site-search");
  const searchResults = document.getElementById("search-results");

  /*
   * Search index generated by Jekyll.
   * Contains ALL published posts, not only the 6
   * cards visible on the homepage.
   */

  let searchIndex = [];

  const searchIndexElement =
    document.getElementById("search-index");

  if (searchIndexElement) {
    try {
      searchIndex =
        JSON.parse(searchIndexElement.textContent);
    } catch (error) {
      console.error(
        "Infograf+ search index error:",
        error
      );

      searchIndex = [];
    }
  }


  /* =====================================================
     OPEN SEARCH
  ===================================================== */

  function showSearch() {

    if (!searchPanel) {
      return;
    }

    searchPanel.hidden = false;

    document.body.style.overflow = "hidden";

    if (searchInput) {

      setTimeout(function () {
        searchInput.focus();
      }, 50);

    }

  }


  /* =====================================================
     CLOSE SEARCH
  ===================================================== */

  function hideSearch() {

    if (!searchPanel) {
      return;
    }

    searchPanel.hidden = true;

    document.body.style.overflow = "";

    if (searchInput) {
      searchInput.value = "";
    }

    if (searchResults) {
      searchResults.innerHTML = "";
    }

  }


  /* =====================================================
     SEARCH BUTTONS
  ===================================================== */

  if (openSearch) {

    openSearch.addEventListener(
      "click",
      showSearch
    );

  }


  if (mobileSearch) {

    mobileSearch.addEventListener(
      "click",
      showSearch
    );

  }


  if (closeSearch) {

    closeSearch.addEventListener(
      "click",
      hideSearch
    );

  }


  /* =====================================================
     CLOSE SEARCH WHEN CLICKING OUTSIDE
  ===================================================== */

  if (searchPanel) {

    searchPanel.addEventListener(
      "click",
      function (event) {

        if (event.target === searchPanel) {
          hideSearch();
        }

      }
    );

  }


  /* =====================================================
     ESC KEY
  ===================================================== */

  document.addEventListener(
    "keydown",
    function (event) {

      if (event.key === "Escape") {
        hideSearch();
      }

    }
  );


  /* =====================================================
     SEARCH RESULTS
  ===================================================== */

  function normalizeArabic(text) {

    return text
      .toString()
      .toLowerCase()
      .trim()

      /* Remove Arabic diacritics */
      .replace(/[\u064B-\u065F\u0670]/g, "")

      /* Normalize Arabic letters */
      .replace(/[إأآا]/g, "ا")
      .replace(/ى/g, "ي")
      .replace(/ة/g, "ه")

      /* Remove tatweel */
      .replace(/ـ/g, "");

  }


  function performSearch(query) {

    if (!searchResults) {
      return;
    }

    const cleanQuery =
      normalizeArabic(query);

    if (!cleanQuery) {

      searchResults.innerHTML = "";

      return;

    }


    /*
     * Search ALL posts.
     */

    const matches =
      searchIndex.filter(function (post) {

        const title =
          normalizeArabic(
            post.title || ""
          );

        const description =
          normalizeArabic(
            post.description || ""
          );

        const category =
          normalizeArabic(
            post.category || ""
          );


        return (
          title.includes(cleanQuery) ||
          description.includes(cleanQuery) ||
          category.includes(cleanQuery)
        );

      });


    /* =================================================
       NO RESULTS
    ================================================= */

    if (matches.length === 0) {

      searchResults.innerHTML =
        '<div class="no-results">' +
        'لا توجد نتائج مطابقة لـ «' +
        escapeHtml(query.trim()) +
        '».' +
        '</div>';

      return;

    }


    /* =================================================
       RESULT COUNT
    ================================================= */

    let html =
      '<div class="search-result-count">' +
      'تم العثور على ' +
      matches.length +
      ' إنفوغرافيك' +
      '</div>';


    /* =================================================
       BUILD RESULTS
    ================================================= */

    matches.forEach(function (post) {

      const title =
        post.title || "إنفوغرافيك";

      const category =
        post.category || "";

      const url =
        post.url || "#";


      html +=
        '<a class="search-result" href="' +
        escapeAttribute(url) +
        '">' +

          '<strong>' +
          escapeHtml(title) +
          '</strong>' +

          (
            category
              ? '<span>' +
                escapeHtml(category) +
                '</span>'
              : ""
          ) +

        '</a>';

    });


    searchResults.innerHTML = html;

  }


  /* =====================================================
     HTML ESCAPE
  ===================================================== */

  function escapeHtml(text) {

    return text
      .toString()
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;")
      .replace(/'/g, "&#039;");

  }


  function escapeAttribute(text) {

    return escapeHtml(text);

  }


  /* =====================================================
     SEARCH INPUT
  ===================================================== */

  if (searchInput) {

    searchInput.addEventListener(
      "input",
      function () {

        performSearch(
          searchInput.value
        );

      }
    );

  }


  /* =====================================================
     HOME CATEGORY FILTER
  ===================================================== */

  const categoryButtons =
    Array.from(
      document.querySelectorAll(
        ".category-chip"
      )
    );


  const homeCards =
    Array.from(
      document.querySelectorAll(
        "#infographic-grid .infographic-card"
      )
    );


  categoryButtons.forEach(
    function (button) {

      /*
       * Only run the JavaScript filter if the
       * button actually has data-category.
       *
       * The homepage category buttons currently
       * link to the categories page, so they remain
       * normal links.
       */

      if (!button.dataset.category) {
        return;
      }


      button.addEventListener(
        "click",
        function (event) {

          event.preventDefault();


          const selectedCategory =
            button.dataset.category ||
            "all";


          categoryButtons.forEach(
            function (item) {

              item.classList.remove(
                "active"
              );

            }
          );


          button.classList.add(
            "active"
          );


          homeCards.forEach(
            function (card) {

              const cardCategory =
                (
                  card.dataset.category ||
                  ""
                ).trim();


              if (
                selectedCategory === "all" ||
                cardCategory === selectedCategory
              ) {

                card.style.display = "";

              } else {

                card.style.display = "none";

              }

            }
          );

        }
      );

    }
  );


  /* =====================================================
     CATEGORY PAGE
  ===================================================== */

  const categoryButtonsPage =
    Array.from(
      document.querySelectorAll(
        ".category-card"
      )
    );


  const categoryCards =
    Array.from(
      document.querySelectorAll(
        "#category-posts .infographic-card"
      )
    );


  const categoryTitle =
    document.getElementById(
      "selected-category-title"
    );


  const categoryCount =
    document.getElementById(
      "selected-category-count"
    );


  const categoryEmpty =
    document.getElementById(
      "category-empty"
    );


  categoryButtonsPage.forEach(
    function (button) {

      button.addEventListener(
        "click",
        function () {

          const selectedCategory =
            button.dataset.category ||
            "all";


          categoryButtonsPage.forEach(
            function (item) {

              item.classList.remove(
                "active"
              );

            }
          );


          button.classList.add(
            "active"
          );


          let visibleCount = 0;


          categoryCards.forEach(
            function (card) {

              const cardCategory =
                (
                  card.dataset.category ||
                  ""
                ).trim();


              if (
                selectedCategory === "all" ||
                cardCategory === selectedCategory
              ) {

                card.style.display = "";

                visibleCount++;

              } else {

                card.style.display =
                  "none";

              }

            }
          );


          if (categoryTitle) {

            if (
              selectedCategory === "all"
            ) {

              categoryTitle.textContent =
                "جميع الإنفوغرافيكات";

            } else {

              categoryTitle.textContent =
                selectedCategory;

            }

          }


          if (categoryCount) {

            categoryCount.textContent =
              visibleCount +
              " إنفوغرافيك";

          }


          if (categoryEmpty) {

            categoryEmpty.hidden =
              visibleCount !== 0;

          }

        }
      );

    }
  );


  /* =====================================================
     INITIALIZE
  ===================================================== */

  console.log(
    "Infograf+ loaded successfully."
  );

  console.log(
    "Search index:",
    searchIndex.length,
    "posts"
  );

});
